export function getLanguageInfo(langCode: string): LanguageItem {
  return ALL_LANGUAGES.find(l => l.code === langCode || l.code.startsWith(langCode)) || ALL_LANGUAGES[0];
}

export function getTranslation(langCode: string, key: string, fallback?: string): string {
  // Normalize code, e.g. en-US -> en
  const baseCode = langCode.split('-')[0];
  const dict = TRANSLATIONS[langCode] || TRANSLATIONS[baseCode] || TRANSLATIONS['en'] || TRANSLATIONS['ar'];
  if (dict && dict[key]) {
    return dict[key];
  }
  // Try fallback in English or Arabic
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  if (TRANSLATIONS['ar'] && TRANSLATIONS['ar'][key]) {
    return TRANSLATIONS['ar'][key];
  }
  return fallback || key;
}
